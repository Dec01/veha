"""Статика вебморды и адреса, по которым страница её грузит.

Страница (`static/index.html`) грузит стили и скрипты по `static/<имя>`. Отдаёт её и
сервер (`veha serve`, `veha demo`), и статический снимок (`veha export-static`), и в
обоих случаях адрес получает версию по содержимому: `static/api.js?v=<хеш>`.

Зачем. Снимок кладут на сайт, и если хостинг кеширует JS и CSS надолго, у того, кто
видел прежний снимок, новая страница встречается со старыми скриптами из кеша браузера —
и падает до принудительного обновления. Версия по содержимому меняет адрес, только когда
изменился файл: неизменный скрипт остаётся в кеше, изменённый грузится заново.

Хеш берётся от содержимого файла с переводами строк, приведёнными к LF. У снимка это
ровно те байты, что лежат в нём рядом со страницей: снимок из рабочей копии с CRLF и из
`git archive` выходит побайтно одинаковым, и адрес меняется вместе с тем, что по нему
лежит. Сервер же отдаёт файлы рабочей копии как есть (на Windows — возможно, с CRLF), а
версию считает тем же кодом от LF: у него хеш — от содержимого, а не от отданных байтов.
Для сервера это неважно — кеш `/` и `/static` у него выключен (`no-store`), версия там —
второй замок и одна страница со снимком. Считается она на каждый запрос страницы.

Как ставится версия. Страница одна, своя и лежит в пакете, поэтому разметка не
разбирается: для каждого имени из :data:`STATIC_FILES` строка `"static/<имя>"` (в
двойных кавычках, как в `index.html`) заменяется на `"static/<имя>?v=<хеш>"`, и
встретиться она обязана ровно один раз — иначе `ValueError`. Что других ссылок на
статику в странице нет (иной формы, от корня домена, на файл вне белого списка), держит
тест над упакованной страницей (`tests/test_export.py`), а не разбор во время работы.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from typing import Dict

#: Что из `static/` грузит страница и что уезжает в снимок. Белый список, а не «всё из
#: каталога»: случайный файл рядом со статикой (заметки, бэкап редактора) не должен
#: попасть на сайт.
STATIC_FILES = ("api.js", "scene3d.js", "map2d.js", "atlas.js", "dock.js", "style.css")
#: Длина версии в адресе — как у сайта partest.ru: первые 10 знаков SHA-256.
VERSION_LEN = 10


def normalized(data: bytes) -> bytes:
    """Переводы строк — как в репозитории (LF), а не как в рабочей копии."""
    return data.replace(b"\r\n", b"\n")


def read_static(static_dir: Path) -> Dict[str, bytes]:
    """Файлы белого списка с переводами строк LF.

    Это байты, которые экспорт пишет в снимок; сервер отдаёт файлы с диска сам и берёт
    отсюда только содержимое для версии.
    """
    return {name: normalized((static_dir / name).read_bytes()) for name in STATIC_FILES}


def version(data: bytes) -> str:
    """Версия файла для адреса: короткий хеш содержимого."""
    return hashlib.sha256(data).hexdigest()[:VERSION_LEN]


def page(static_dir: Path, files: Dict[str, bytes]) -> str:
    """Разметка страницы, где каждый адрес статики несёт версию своего содержимого.

    *files* — содержимое статики (:func:`read_static`): версия считается от него, а не
    от файла на диске, прочитанного ещё раз. Адрес `"static/<имя>"` каждого файла должен
    встретиться в странице ровно один раз — иначе `ValueError`.
    """
    html = normalized((static_dir / "index.html").read_bytes()).decode("utf-8")
    for name in STATIC_FILES:
        ref = f'"static/{name}"'
        n = html.count(ref)
        if n != 1:
            raise ValueError(f"адрес {ref} должен встретиться в index.html ровно один раз, "
                             f"а встретился: {n} — версию ?v= ставить некуда или "
                             "неоднозначно")
        html = html.replace(ref, f'"static/{name}?v={version(files[name])}"')
    return html
